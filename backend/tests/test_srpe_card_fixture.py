"""`frontend/src/fixtures/srpe31Oct.json` is what the real routes return for the operator's real starting state, not
a response the author typed (FEEDBACK section 48: a form tested only on fixtures its author constructed is untested
where it breaks).

The state is the 31 Oct 2026 case, built from rows: a 55-min Hevy-only workout and a 52-min Garmin Pilates that
arrived through Health Connect, both unrated, on the day being closed out; yesterday (30 Oct) missed its close-out
and holds one unrated Hevy workout and one Garmin-rated ride; and earlier unrated sessions the day fill had
covered. The card tests under `frontend/src/` replay these responses.

This test regenerates the file from the live routes and fails if it differs, so the frontend can never be driven
by a response the server would no longer give. To refresh after a deliberate route change:

    REGEN_SRPE_FIXTURE=1 python -m pytest tests/test_srpe_card_fixture.py
"""
import json
import os
from datetime import date, datetime, timedelta, timezone
from pathlib import Path

import pytest
from fastapi import FastAPI
from fastapi.testclient import TestClient

import models
import routers.checkin_v2 as c2
import srpe_store
from auth import get_current_user
from database import get_db
from routers import srpe_ratings

FIXTURE = Path(__file__).resolve().parents[2] / "frontend" / "src" / "fixtures" / "srpe31Oct.json"
TODAY = date(2026, 10, 31)
GARMIN_PKG = "com.garmin.android.apps.connectmobile"


def _utc(day, hh, mm=0):
    return datetime(2026, 10, day, hh, mm, tzinfo=timezone.utc)      # +10h: UTC 02:00 is 12:00 the same AEST day


def _hevy(db, uid, hid, title, start, minutes):
    db.add(models.HevyWorkout(hevy_id=hid, user_id=uid, start_time=start, end_time=start + timedelta(minutes=minutes),
                              title=title, raw={}))


def _aero(db, uid, sid, sport, start, minutes, source="health_connect"):
    db.add(models.AerobicSession(
        user_id=uid, source=source, source_session_id=sid, session_date=(start + timedelta(hours=10)).date(),
        start_time=start, stop_time=start + timedelta(minutes=minutes), sport_name=sport,
        duration_minutes=float(minutes), source_package=GARMIN_PKG, z2_seconds=600))


@pytest.fixture
def real_state(db_session, monkeypatch):
    monkeypatch.setattr(c2, "_today_aest", lambda: TODAY)
    u = models.User(email="op@x.io", hashed_password="x")
    db_session.add(u)
    db_session.commit()
    # the open close-out day: the 31 Oct pair, both unrated
    _hevy(db_session, u.id, "hevy-0031", "Upper body", _utc(31, 2), 55)
    _aero(db_session, u.id, "hc-pilates-31", "Pilates", _utc(31, 8), 52)
    # yesterday, whose close-out was missed: an unrated workout and a ride Garmin rated
    _hevy(db_session, u.id, "hevy-0030", "Lower body", _utc(30, 1), 60)
    _aero(db_session, u.id, "hc-ride-30", "Biking", _utc(30, 8), 40)
    # earlier sessions the day fill used to cover
    _hevy(db_session, u.id, "hevy-0025", "Pull", _utc(25, 2), 50)
    _aero(db_session, u.id, "hc-pilates-27", "Pilates", _utc(27, 8), 45)
    # a history row so yesterday's missed close-out is offered (the offer needs a record on/before yesterday)
    db_session.add(models.DailyRecord(user_id=u.id, date=date(2026, 10, 29), am_timestamp=_utc(29, 0),
                                      pm_timestamp=_utc(29, 12), today_rating=3))
    db_session.commit()
    ride = db_session.query(models.AerobicSession).filter_by(source_session_id="hc-ride-30").one()
    srpe_store.record_observation(db_session, u.id, source="garmin", source_activity_ref="g-ride-30",
                                  start=_utc(30, 8), stop=_utc(30, 8) + timedelta(minutes=40), rpe_raw=60,
                                  raw_scale="garmin_0_100", now=_utc(30, 11))
    assert ride is not None
    return u


def _client(db, user):
    app = FastAPI()
    app.include_router(c2.router)
    app.include_router(srpe_ratings.router)
    app.dependency_overrides[get_db] = lambda: db
    app.dependency_overrides[get_current_user] = lambda: user
    return TestClient(app)


def _get(c, url, **params):
    r = c.get(url, params=params)
    assert r.status_code == 200, (url, r.text)
    return r.json()


def _live(db, user):
    c = _client(db, user)
    missed = c2._missed_pm(user.id, TODAY, db)
    assert missed is not None, "the 30 Oct close-out must be offered"
    return {
        "_about": "Generated by backend/tests/test_srpe_card_fixture.py from the real routes. Do not edit by hand.",
        "closeout": {
            "today": _get(c, "/checkin-v2/today"),
            "sessions": _get(c, "/checkin-v2/srpe/sessions"),
            "earlier": _get(c, "/checkin-v2/srpe/earlier"),
        },
        "catchup": {
            "missed_pm": json.loads(missed.model_dump_json()),
            "sessions": _get(c, "/checkin-v2/srpe/sessions", since="2026-10-30", until="2026-10-30"),
            "earlier": _get(c, "/checkin-v2/srpe/earlier", before="2026-10-30"),
        },
    }


def _render(obj) -> str:
    return json.dumps(obj, indent=2, sort_keys=True) + "\n"


def test_the_committed_fixture_is_what_the_routes_return_for_the_real_state(db_session, real_state):
    text = _render(_live(db_session, real_state))
    if os.environ.get("REGEN_SRPE_FIXTURE") == "1":
        FIXTURE.write_text(text, encoding="utf-8")
    assert FIXTURE.read_text(encoding="utf-8") == text, (
        "the srpe card fixture no longer matches the routes; regenerate with REGEN_SRPE_FIXTURE=1 and review the diff")


def test_the_real_state_is_the_31_oct_shape(db_session, real_state):
    """The facts the card tests lean on, asserted at the source: two unrated asks today, one rated read-only
    yesterday beside one ask, and unrated earlier sessions for the backfill."""
    live = _live(db_session, real_state)
    today = [(s["kind"], s["label"], s["minutes"], s["rpe"]) for s in live["closeout"]["sessions"]["sessions"]]
    assert today == [("hevy", "Upper body", 55.0, None), ("aerobic", "Pilates", 52.0, None)]
    assert live["closeout"]["today"]["srpe_needed"] is True and "session_rpe" not in live["closeout"]["today"]
    yday = [(s["label"], s["rpe"], s["source"]) for s in live["catchup"]["sessions"]["sessions"]]
    assert yday == [("Lower body", None, None), ("Biking", 6.0, "garmin")]
    assert [s["label"] for s in live["closeout"]["earlier"]["sessions"]] == ["Pull", "Pilates", "Lower body"]
    assert live["catchup"]["missed_pm"]["srpe_needed"] is True
